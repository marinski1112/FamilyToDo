import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {DatabaseSync} from 'node:sqlite';
import {transform} from 'esbuild';

const source=fs.readFileSync('src/family-daily-journal.ts','utf8');
const compiled=await transform(source.replace(/^import .*;\n/gm,''),{loader:'ts',format:'cjs'});
const db=new DatabaseSync(':memory:');
db.exec(`CREATE TABLE family_daily_journals(id INTEGER PRIMARY KEY,family_id INTEGER,journal_date TEXT,summary_text TEXT,location_json TEXT,tasks_json TEXT,housework_json TEXT,generated_at TEXT,updated_at TEXT,content_version INTEGER,storage_tier TEXT,archive_object_key TEXT,archived_at TEXT,UNIQUE(family_id,journal_date));
CREATE TABLE members(id INTEGER PRIMARY KEY,family_id INTEGER,name TEXT);
CREATE TABLE location_devices(member_id INTEGER,enabled INTEGER,sharing_enabled INTEGER,revoked_at TEXT);
CREATE TABLE location_history_archive_days(family_id INTEGER,member_id INTEGER,local_date TEXT,route_point_count INTEGER);
CREATE TABLE location_history_stays(id INTEGER PRIMARY KEY,family_id INTEGER,member_id INTEGER,local_date TEXT,started_at TEXT,ended_at TEXT,duration_minutes INTEGER,place_label TEXT,address_label TEXT);`);
const adapter={prepare(sql){const stmt=db.prepare(sql);let args=[];return {bind(...values){args=values;return this;},async first(){return stmt.get(...args)||null;},async all(){return {results:stmt.all(...args)};},async run(){return {meta:{changes:Number(stmt.run(...args).changes)}};}};}};
const context=vm.createContext({module:{exports:{}},exports:{},formatFamilyDateTime:()=>'',DEFAULT_FAMILY_TIMEZONE:'Asia/Tokyo'});context.exports=context.module.exports;
vm.runInContext(compiled.code,context);
const archivedDay=new Date(Date.now()-86400000).toISOString().slice(0,10);
db.prepare("INSERT INTO members VALUES(1,1,'A')").run();
db.prepare('INSERT INTO location_devices VALUES(1,0,0,?)').run('2026-09-25');
db.prepare('INSERT INTO location_history_archive_days VALUES(1,1,?,72)').run(archivedDay);
db.prepare("INSERT INTO location_history_stays(family_id,member_id,local_date,started_at,ended_at,duration_minutes,place_label) VALUES(1,1,?,'2026-09-24T02:00:00Z','2026-09-24T04:00:00Z',120,'自宅')").run(archivedDay);
const past=await vm.runInContext('readLocation',context)(adapter,1,archivedDay);
assert.equal(past.length,1,'revoking a device does not retroactively suppress its archived day');
assert.equal(past[0].stays.length,1);
vm.runInContext(`readTasks=async()=>[];readHousework=async()=>[];readLocation=async()=>[];`,context);
const day=new Date(Date.now()-86400000).toISOString().slice(0,10);
await context.module.exports.generateFamilyDailyJournal(adapter,1,day);
let row=db.prepare('SELECT * FROM family_daily_journals WHERE family_id=1').get();
assert.equal(row.content_version,1);
await context.module.exports.generateFamilyDailyJournal(adapter,1,day);
assert.equal(db.prepare('SELECT content_version FROM family_daily_journals').get().content_version,1,'elapsed time alone cannot regenerate AI');
vm.runInContext(`readLocation=async()=>[{memberId:1,name:'A',routePointCount:72,stays:[{from:'2026-09-24T02:00:00Z',to:'2026-09-24T04:00:00Z',minutes:120,place:'自宅'}]}];`,context);
await context.module.exports.repairFamilyDailyJournal(adapter,1,day);
row=db.prepare('SELECT * FROM family_daily_journals').get();assert.equal(row.content_version,2);assert.equal(JSON.parse(row.location_json).length,1);
vm.runInContext('readLocation=async()=>[];',context);
await context.module.exports.repairFamilyDailyJournal(adapter,1,day);
row=db.prepare('SELECT * FROM family_daily_journals').get();assert.equal(row.content_version,2,'sharing stopped later cannot erase the finalized snapshot');assert.equal(JSON.parse(row.location_json).length,1);
assert.ok(!source.includes('sharedLocationMembers.has(member.memberId)'),'render must not hide the saved snapshot');
db.close();
console.log('journal repair: identical snapshots do not bump version; new archive repairs once; historical snapshot remains after sharing stops');
