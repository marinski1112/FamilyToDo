import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {DatabaseSync} from 'node:sqlite';
import {transform} from 'esbuild';

const source=fs.readFileSync('src/journal-location-diagnostics.ts','utf8');
const compiled=await transform(source.replace(/^import .*;\n/gm,''),{loader:'ts',format:'cjs'});
const db=new DatabaseSync(':memory:');
db.exec(`CREATE TABLE members(id INTEGER,family_id INTEGER,active INTEGER);
CREATE TABLE member_location_history(id INTEGER PRIMARY KEY,family_id INTEGER,member_id INTEGER,recorded_at TEXT,accuracy_meters REAL);
CREATE TABLE location_devices(member_id INTEGER,family_id INTEGER,enabled INTEGER,sharing_enabled INTEGER,revoked_at TEXT);
CREATE TABLE location_history_archive_days(family_id INTEGER,member_id INTEGER,local_date TEXT,raw_point_count INTEGER,route_point_count INTEGER);
CREATE TABLE location_history_stays(family_id INTEGER,local_date TEXT);
CREATE TABLE family_daily_journals(id INTEGER,family_id INTEGER,journal_date TEXT,storage_tier TEXT,generated_at TEXT,content_version INTEGER,ai_status TEXT,ai_source_content_version INTEGER,location_json TEXT);
INSERT INTO members VALUES(1,10,1),(2,20,1);
INSERT INTO member_location_history(family_id,member_id,recorded_at,accuracy_meters) VALUES(10,1,'2026-09-23T15:00:00.000Z',20),(10,1,'2026-09-23T15:00:20.000Z',20),(10,1,'2026-09-23T15:01:20.000Z',120),(10,1,'2026-09-23T15:31:20.000Z',120),(10,1,'2026-09-24T14:59:59.999Z',NULL),(20,2,'2026-09-24T01:00:00.000Z',20),(10,1,'2026-09-24T15:00:00.000Z',20);
INSERT INTO location_devices VALUES(1,10,1,0,NULL),(2,20,1,1,NULL);
INSERT INTO location_history_archive_days VALUES(10,1,'2026-09-24',5,3),(20,2,'2026-09-24',99,88);
INSERT INTO location_history_stays VALUES(10,'2026-09-24'),(20,'2026-09-24');
INSERT INTO family_daily_journals VALUES(7,10,'2026-09-24','HOT','2026-09-25T01:00:00Z',1,'AI_OK',1,'[{"memberId":1,"stays":[{},{}]}]'),(8,20,'2026-09-24','HOT','2026-09-25T01:00:00Z',1,'AI_OK',1,'[]');`);
const adapter={prepare(sql){const stmt=db.prepare(sql);return {bind(...args){return {first:async()=>stmt.get(...args)}}}}};
const context=vm.createContext({module:{exports:{}},exports:{},json:(data,status=200)=>new Response(JSON.stringify(data),{status,headers:{'content-type':'application/json'}}),familyNow:()=> '2026-09-25 10:00:00',DEFAULT_FAMILY_TIMEZONE:'Asia/Tokyo',Date,Number,String,URL,Response});
context.exports=context.module.exports;
vm.runInContext(compiled.code,context);
const run=async(member,method='GET')=>{const response=await context.module.exports.journalLocationDiagnostics(new Request('https://example.test/api/settings/diagnostics-detail?issue=journal_location&date=2026-09-24',{method}),{member,env:{DB:adapter}});return {status:response.status,data:await response.json()};};
assert.equal((await run(null)).status,401);
assert.equal((await run({family_id:10,role:'MEMBER'})).status,403);
assert.equal((await run({family_id:10,role:'ADMIN'},'POST')).status,405);
const {status,data}=await run({family_id:10,role:'OWNER'});
assert.equal(status,200);
assert.equal(data.raw_history_points,5,'JST day includes both UTC edges, excluding the next midnight');
assert.equal(data.raw_history_members,1);
assert.equal(data.raw_history_members_over_archive_limit,0);
assert.equal(data.raw_accuracy_le_100,2);
assert.equal(data.raw_accuracy_le_150,4);
assert.equal(data.raw_pairs_under_one_minute,1);
assert.equal(data.raw_pairs_one_to_thirty_minutes,2,'exact one and thirty minute intervals remain eligible');
assert.equal(data.raw_pairs_over_thirty_minutes,1);
assert.equal(data.archive_members,1);
assert.equal(data.archive_members_currently_shared,0);
assert.equal(data.archive_stays,1);
assert.equal(data.journal_saved_members,1);
assert.equal(data.journal_saved_stays,2);
assert.equal(data.journal_content_version,1);
assert.ok(!JSON.stringify(data).includes('memberId')&&!JSON.stringify(data).includes('location_json'));
db.close();
console.log('journal location diagnostics: family-scoped, admin-only archive/snapshot counts without raw location');
