import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { stripTypeScriptTypes } from 'node:module';
await import('./line-morning-five-facts-contract.mjs');
const source=p=>fs.readFileSync(p,'utf8');
const compile=s=>stripTypeScriptTypes(s.replace(/^import .*$/gm,''),{mode:'strip'}).replace(/export /g,'');
const daily=source('src/line-daily-digest.ts');
const helper=source('src/line-digest-generation.ts');
const settings=source('src/settings-ai-diagnostics.ts');
const context=vm.createContext({Set,Number,Array});
vm.runInContext(compile(helper)+'\nthis.sanitize=safeDigestAttempts;',context);
assert.equal(JSON.stringify(context.sanitize([{model:'test',httpStatus:200,stage:'COMPLETE',reason:'OK',durationMs:10,secret:'hidden',prompt:'hidden'}])),JSON.stringify([{model:'test',httpStatus:200,stage:'COMPLETE',reason:'OK',durationMs:10}]));
assert.equal(context.sanitize([{model:'secret/value',stage:'COMPLETE',reason:'OK'}]).length,0);
const diagnosticContext=vm.createContext({Set,Number,String,Array,JSON});
vm.runInContext(compile(helper)+'\n'+compile(settings)+'\nthis.morningItem=morningItem;',diagnosticContext);
const noAttempt=diagnosticContext.morningItem({frame_json:JSON.stringify({generation:{status:'FALLBACK',reason:'BUDGET_OR_CIRCUIT',model:'candidate-model',attempts:[]}}),request_count:0,finalized:1,local_date:'2026-09-10',updated_at:'2026-09-10T00:00:00Z'});
assert.equal(noAttempt.ai_called,false);assert.equal(noAttempt.model,null);
const oneAttempt=diagnosticContext.morningItem({frame_json:JSON.stringify({generation:{status:'FALLBACK',reason:'BUDGET_OR_CIRCUIT',model:'never-called-retry',attempts:[{model:'called-model',httpStatus:403,stage:'PROVIDER_RESPONSE',reason:'HTTP_ERROR',durationMs:12}]}}),request_count:1,finalized:1,local_date:'2026-09-10',updated_at:'2026-09-10T00:00:00Z'});
assert.equal(oneAttempt.ai_called,true);assert.equal(oneAttempt.model,'called-model');assert.equal(oneAttempt.http_status,403);
assert.equal(diagnosticContext.morningItem({frame_json:'{}',request_count:0,finalized:1,local_date:'2026-09-10:v4:abc123'}).local_date,'2026-09-10','destination hash must not appear in admin diagnostics');
assert.ok(settings.indexOf('if(!baseResponse.ok)return baseResponse')<settings.indexOf('SELECT local_date'));
assert.ok(settings.includes('WHERE family_id=? AND finalized=1'));
assert.equal((daily.match(/geminiFetch\(/g)||[]).length,1);
console.log('Morning attempt evidence: bounded diagnostic fields, actual-model display, and authorization contracts pass.');
